val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(key: String): String? = System.getenv(key) ?: localProps.getProperty(key)

val appVersion = providers.gradleProperty("diary.version").get()
val appVersionCode = appVersion.split(".").map { it.toInt() }.let { (a, b, c) -> a * 10000 + b * 100 + c }

android {
    namespace = "ru.diary.training"
    compileSdk = 36

    defaultConfig {
        applicationId = "ru.diary.training"
        minSdk = 26
        targetSdk = 36
        versionCode = appVersionCode
        versionName = appVersion
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        // Один и тот же ключ для обоих приложений нужен для обмена данными (signature-permission).
        // Ключ и пароли берутся из local.properties или переменных окружения и в git не попадают.
        val storePath = secret("DIARY_KEYSTORE")
        if (storePath != null) {
            create("release") {
                storeFile = file(storePath)
                storePassword = secret("DIARY_KEYSTORE_PASSWORD")
                keyAlias = secret("DIARY_KEY_ALIAS")
                keyPassword = secret("DIARY_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    lint {
        // Версии библиотек закреплены осознанно: обновление проходит отдельным шагом с проверкой сборки.
        disable += setOf("GradleDependency", "NewerVersionAvailable", "AndroidGradlePluginVersion", "ObsoleteSdkInt")
        abortOnError = true
    }
    buildFeatures { compose = true }
    testOptions { unitTests.isIncludeAndroidResources = true }
}

